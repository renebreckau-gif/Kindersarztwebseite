# Isolated LOCAL development PostgreSQL cluster for the Praxis Cockpit backend.
#
#   powershell -ExecutionPolicy Bypass -File scripts/db-dev.ps1 <init|start|stop|status>
#
# - Own data directory outside the repository and outside OneDrive:
#   %LOCALAPPDATA%\kinderarzt-postgres-dev
# - Own port 5433, bound to 127.0.0.1 only (never exposed to the network)
# - scram-sha-256 password authentication (never trust)
# - Never touches the system PostgreSQL service on port 5432
# - Contains no passwords: `init` generates them and writes them ONLY to the git-ignored
#   .env.local (they are never printed)
# - Controls only this cluster via pg_ctl and its data directory (never kills processes)

param([Parameter(Mandatory = $true)][ValidateSet("init", "start", "stop", "status")][string]$Command)

$ErrorActionPreference = "Stop"
$PgBin = if ($env:KINDERARZT_PG_BIN) { $env:KINDERARZT_PG_BIN } else { "C:\Program Files\PostgreSQL\16\bin" }
$Root = Join-Path $env:LOCALAPPDATA "kinderarzt-postgres-dev"
$Data = Join-Path $Root "data"
$Log = Join-Path $Root "postgres.log"
$Port = 5433
$HostAddr = "127.0.0.1"
$Super = "kinderarzt_dev_super"
$AppRole = "kinderarzt_app"
$AppDb = "kinderarzt_staging_dev"
$TestDb = "kinderarzt_staging_test"
$EnvFile = Join-Path (Split-Path $PSScriptRoot -Parent) ".env.local"

function Pg([string]$exe) { Join-Path $PgBin "$exe.exe" }
function New-Secret { $b = New-Object byte[] 32; [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b); ($b | ForEach-Object { $_.ToString("x2") }) -join "" }
function Assert-Ignored {
  & git -C (Split-Path $EnvFile -Parent) check-ignore -q $EnvFile
  if ($LASTEXITCODE -ne 0) { throw ".env.local is not git-ignored - refusing to write secrets." }
}
function Start-Cluster {
  # Detached start: pg_ctl's server child must not inherit this console's pipes (that blocks callers).
  $ctl = Pg "pg_ctl"
  Start-Process -FilePath "cmd.exe" -ArgumentList "/c", "`"`"$ctl`" -D `"$Data`" -l `"$Log`" start > NUL 2>&1`"" -WindowStyle Hidden | Out-Null
  for ($i = 0; $i -lt 60; $i++) {
    & (Pg "pg_isready") -q -h $HostAddr -p $Port
    if ($LASTEXITCODE -eq 0) { return }
    Start-Sleep -Milliseconds 500
  }
  throw "Cluster did not become ready - see $Log"
}
function Invoke-Sql([string]$db, [string]$sql, [string]$password) {
  $env:PGPASSWORD = $password
  try { & (Pg "psql") -w -v ON_ERROR_STOP=1 -q -h $HostAddr -p $Port -U $Super -d $db -c $sql | Out-Null; if ($LASTEXITCODE -ne 0) { throw "psql failed" } }
  finally { Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue }
}

switch ($Command) {
  "init" {
    if (Test-Path $Data) { throw "Cluster already exists at $Data - nothing changed." }
    Assert-Ignored
    if ((Test-Path $EnvFile) -and (Select-String -Path $EnvFile -Pattern '^(DATABASE_URI|PAYLOAD_SECRET)=' -Quiet)) { throw ".env.local already contains backend values - refusing to overwrite." }
    New-Item -ItemType Directory -Force $Root | Out-Null
    $superPw = New-Secret; $appPw = New-Secret; $payloadSecret = New-Secret
    $pwFile = Join-Path $Root "init-pw.tmp"
    [IO.File]::WriteAllText($pwFile, $superPw)
    try {
      & (Pg "initdb") -D $Data -U $Super --pwfile=$pwFile --auth=scram-sha-256 --encoding=UTF8 --locale=C | Out-Null
      if ($LASTEXITCODE -ne 0) { throw "initdb failed" }
    } finally { Remove-Item $pwFile -Force }
    Add-Content -Path (Join-Path $Data "postgresql.conf") -Encoding ascii "`n# kinderarzt dev cluster`nlisten_addresses = '$HostAddr'`nport = $Port`npassword_encryption = 'scram-sha-256'`n"
    # Loopback IPv4 only, password authentication only.
    [IO.File]::WriteAllText((Join-Path $Data "pg_hba.conf"), "# kinderarzt dev cluster: loopback only, scram-sha-256 only`nhost all all 127.0.0.1/32 scram-sha-256`n")
    # Persist the generated values first (git-ignored), so a later failure never loses them.
    $lines = @(
      "# Local development only (generated by scripts/db-dev.ps1). Never commit. Never reuse elsewhere.",
      "DATABASE_URI=postgresql://${AppRole}:${appPw}@${HostAddr}:${Port}/${AppDb}",
      "TEST_DATABASE_URI=postgresql://${AppRole}:${appPw}@${HostAddr}:${Port}/${TestDb}",
      "PAYLOAD_SECRET=$payloadSecret",
      "# Cluster superuser - maintenance only, never used by the application.",
      "DEV_DB_SUPERUSER_URI=postgresql://${Super}:${superPw}@${HostAddr}:${Port}/postgres"
    )
    Add-Content -Path $EnvFile -Encoding ascii ($lines -join "`n")
    Start-Cluster
    Invoke-Sql "postgres" "CREATE ROLE $AppRole LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD '$appPw';" $superPw
    foreach ($db in @($AppDb, $TestDb)) {
      Invoke-Sql "postgres" "CREATE DATABASE $db OWNER $AppRole ENCODING 'UTF8';" $superPw
      Invoke-Sql $db "ALTER SCHEMA public OWNER TO $AppRole; REVOKE ALL ON DATABASE $db FROM PUBLIC;" $superPw
    }
    "Cluster created at $Data (port $Port, $HostAddr only). Databases: $AppDb, $TestDb (owner $AppRole). Secrets written to .env.local (not shown)."
  }
  "start" {
    & (Pg "pg_ctl") -D $Data status | Out-Null
    if ($LASTEXITCODE -eq 0) { "Already running (port $Port)."; break }
    Start-Cluster
    "Started (port $Port, $HostAddr only)."
  }
  "stop" { & (Pg "pg_ctl") -D $Data -w -m fast stop 2>&1 | Out-Null; "Stopped." }
  "status" {
    & (Pg "pg_ctl") -D $Data status | Select-Object -First 1
    & (Pg "pg_isready") -h $HostAddr -p $Port
  }
}
