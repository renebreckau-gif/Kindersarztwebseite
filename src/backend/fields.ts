// Shared field definitions for the practice backend (type-only Payload import).
// Dates are Europe/Berlin calendar dates stored as text "YYYY-MM-DD" (never timestamps), times
// as "HH:MM" — exactly the domain's LocalDate / LocalTime, so the engine sees no timezone drift.

import type { Field } from "payload";
import { isLocalDate } from "../domain/time.ts";

const TIME = /^([01]\d|2[0-3]):[0-5]\d$/;

export const localDate = (name: string, label: string, required = true): Field => ({
  name,
  label,
  type: "text",
  required,
  // Format AND a real calendar day (no "2026-02-30").
  validate: (v: unknown) => (!v && !required) || (typeof v === "string" && isLocalDate(v)) || "Bitte ein gültiges Datum im Format JJJJ-MM-TT angeben.",
});

export const localTime = (name: string, label: string): Field => ({
  name,
  label,
  type: "text",
  required: true,
  validate: (v: unknown) => (typeof v === "string" && TIME.test(v)) || "Bitte eine Uhrzeit im Format HH:MM angeben.",
});

export const recordId: Field = {
  name: "recordId",
  label: "Datensatz-ID",
  type: "text",
  required: true,
  unique: true,
  index: true,
  admin: { readOnly: true, description: "Stabile ID für die Praxis-Puls-Logik." },
};

export const CONSULTATION_TYPE_OPTIONS = ["GENERAL", "ACUTE", "APPOINTMENT", "HEALTHY_ONLY", "OTHER"].map((v) => ({ label: v, value: v }));

/**
 * FactVerification as a group. `verifiedBy`, `lastVerified` and `reviewDue` are generated by
 * the provenance hook from the logged-in account — read-only in every UI, client values ignored.
 */
export const verification = (name = "verification", label = "Bestätigung"): Field => ({
  name,
  label,
  type: "group",
  fields: [
    {
      name: "status",
      type: "select",
      required: true,
      defaultValue: "TO_BE_CONFIRMED",
      options: [
        { label: "bestätigt", value: "VERIFIED_CURRENT" },
        { label: "zu bestätigen", value: "TO_BE_CONFIRMED" },
        { label: "veraltet – nie veröffentlichen", value: "OUTDATED_DO_NOT_PUBLISH" },
      ],
      admin: { readOnly: true },
    },
    { name: "lastVerified", type: "text", admin: { readOnly: true } },
    { name: "verifiedBy", type: "text", admin: { readOnly: true } },
    { name: "reviewDue", type: "text", admin: { readOnly: true } },
    { name: "sourceIds", type: "array", fields: [{ name: "sourceId", type: "text", required: true }], admin: { readOnly: true } },
    { name: "internalNotes", type: "textarea", maxLength: 200, admin: { description: "Intern, nie öffentlich. Keine Patientendaten." } },
  ],
});
