// Parsing of workflow inputs from query strings / form posts (pure). Only the fields a person
// actually chooses are read — never a date, role, provenance or change-set id.

import { MAX_PERIODS, type ClosedTodayInput, type EarlyCloseInput, type PlannedClosureInput, type PlannedKind, type PublicReason, type ReplacementMode } from "./types.ts";

type Get = (name: string) => string | undefined;
type GetAll = (name: string) => string[];

export const fromSearch = (q: Record<string, string | string[] | undefined>): { get: Get; getAll: GetAll } => ({
  get: (n) => (Array.isArray(q[n]) ? (q[n] as string[])[0] : (q[n] as string | undefined)),
  getAll: (n) => (Array.isArray(q[n]) ? (q[n] as string[]) : q[n] ? [q[n] as string] : []),
});

export const fromForm = (f: FormData): { get: Get; getAll: GetAll } => ({
  get: (n) => (typeof f.get(n) === "string" ? (f.get(n) as string) : undefined),
  getAll: (n) => f.getAll(n).filter((v): v is string => typeof v === "string"),
});

const REASONS: PublicReason[] = ["KRANKHEIT", "FORTBILDUNG", "TECHNIK", "KEINER", "SONSTIGES"];

export function parseEarlyClose(src: { get: Get }): EarlyCloseInput {
  return { time: (src.get("zeit") ?? "").trim(), message: src.get("hinweis") ?? undefined, ...(src.get("ersetzen") === "1" ? { replaceExisting: true } : {}) };
}

export function parseClosedToday(src: { get: Get; getAll: GetAll }): ClosedTodayInput {
  const reason = src.get("grund") as PublicReason | undefined;
  return {
    mode: src.get("modus") === "uhrzeit" ? "FROM_TIME" : "NOW",
    time: src.get("zeit")?.trim() || undefined,
    reason: reason && REASONS.includes(reason) ? reason : "KEINER",
    otherText: src.get("sonstiges") ?? undefined,
    replacementIds: src.getAll("vertretung"),
    ...(src.get("ersetzen") === "1" ? { replaceExisting: true } : {}),
  };
}

/** Query string that reproduces an input (for "back to the preview" after a blocked publish). */
export function earlyCloseQuery(i: EarlyCloseInput): string {
  const p = new URLSearchParams({ zeit: i.time });
  if (i.message) p.set("hinweis", i.message);
  if (i.replaceExisting) p.set("ersetzen", "1");
  return p.toString();
}

export function closedTodayQuery(i: ClosedTodayInput): string {
  const p = new URLSearchParams({ modus: i.mode === "FROM_TIME" ? "uhrzeit" : "sofort", grund: i.reason });
  if (i.time) p.set("zeit", i.time);
  if (i.otherText) p.set("sonstiges", i.otherText);
  for (const id of i.replacementIds) p.append("vertretung", id);
  if (i.replaceExisting) p.set("ersetzen", "1");
  return p.toString();
}

// ---------------------------------------------------------------- 7.5 Urlaub / Schließzeit (09.5C)

export const KIND_PARAM: Record<string, PlannedKind> = { urlaub: "VACATION", fortbildung: "TRAINING", sonstiges: "OTHER" };
export const KIND_SLUG: Record<PlannedKind, string> = { VACATION: "urlaub", TRAINING: "fortbildung", OTHER: "sonstiges" };
const MODE_PARAM: Record<string, ReplacementMode> = { ganz: "GANZ", teilen: "TEILEN", keine: "KEINE" };
export const MODE_SLUG: Record<ReplacementMode, string> = { GANZ: "ganz", TEILEN: "teilen", KEINE: "keine" };
/** Domain record ids generated by the cockpit (and the seed) — anything else is not looked up. */
export const RECORD_ID = /^[a-z0-9][a-z0-9-]{0,79}$/;

const trimmed = (v: string | undefined) => v?.trim() ?? "";

/**
 * The planned-closure input. Period rows are z0_…, z1_… (von / bis / praxis). The record id of an
 * edit only NAMES the target; the server re-loads that ACTIVE record and never trusts its content.
 */
export function parsePlannedClosure(src: { get: Get }): PlannedClosureInput {
  const periods: PlannedClosureInput["periods"] = [];
  for (let i = 0; i < MAX_PERIODS; i++) {
    const row = [src.get(`z${i}_von`), src.get(`z${i}_bis`), src.get(`z${i}_praxis`)];
    if (row.every((v) => v === undefined)) continue;
    periods.push({ from: trimmed(row[0]), to: trimmed(row[1]), practice: trimmed(row[2]) });
  }
  const eintrag = src.get("eintrag");
  return {
    ...(eintrag !== undefined ? { recordId: RECORD_ID.test(eintrag) ? eintrag : "" } : {}),
    kind: KIND_PARAM[src.get("art") ?? ""],
    from: trimmed(src.get("von")),
    to: trimmed(src.get("bis")),
    announceFrom: trimmed(src.get("ankuendigen")),
    message: src.get("hinweis") ?? undefined,
    mode: MODE_PARAM[src.get("vertretung") ?? ""],
    practice: trimmed(src.get("praxis")) || undefined,
    periods,
    gapsAccepted: src.get("luecke") === "1",
  };
}

/** Query string that reproduces a planned-closure input (record id travels in the path, not here). */
export function plannedQuery(i: PlannedClosureInput): string {
  const p = new URLSearchParams();
  if (i.kind) p.set("art", KIND_SLUG[i.kind]);
  p.set("von", i.from);
  p.set("bis", i.to);
  p.set("ankuendigen", i.announceFrom);
  if (i.message) p.set("hinweis", i.message);
  if (i.mode) p.set("vertretung", MODE_SLUG[i.mode]);
  if (i.practice) p.set("praxis", i.practice);
  i.periods.slice(0, MAX_PERIODS).forEach((r, n) => {
    p.set(`z${n}_von`, r.from);
    p.set(`z${n}_bis`, r.to);
    p.set(`z${n}_praxis`, r.practice);
  });
  if (i.gapsAccepted) p.set("luecke", "1");
  return p.toString();
}

/** Form-structure buttons (GET only): "teilen", "entfernen-N", "anpassen-N". */
export function parsePeriodAction(src: { get: Get }): { kind: "SPLIT" } | { kind: "REMOVE" | "FIX"; index: number } | undefined {
  const a = src.get("aktion") ?? "";
  if (a === "teilen") return { kind: "SPLIT" };
  const m = a.match(/^(entfernen|anpassen)-([0-7])$/);
  return m ? { kind: m[1] === "entfernen" ? "REMOVE" : "FIX", index: Number(m[2]) } : undefined;
}
